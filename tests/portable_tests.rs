/// Regenerate the Rust-produced interop artifacts that the TS side verifies
/// (`wallet-toolbox/test/storage/portable-rust-verify.test.ts`): restore the
/// TS fixture, then export it back out through the full Rust BRC-38 and
/// BRC-39 (default KDF, random salt/nonce) paths. Set RUST_ARTIFACT_OUT=1 to
/// rewrite `tests/fixtures/portable/{brc38,brc39}-rust-export.*`; without it
/// the test only proves the artifacts can be produced.
#[tokio::test]
async fn generate_rust_export_artifacts() {
    let document = parse_brc38_json(&fixture_string("brc38-ts-export.json")).unwrap();
    let target = empty_storage().await;
    import_brc38(
        &target,
        &document,
        &Brc38ImportOptions {
            mode: ImportMode::Restore,
        },
    )
    .await
    .unwrap();

    // One export, encrypted as-is, so the .json and .bin artifacts carry the
    // same document (including exportedAt).
    let exported =
        bsv_wallet_toolbox::storage::portable::export_brc38(&target, &fixture_identity_key())
            .await
            .unwrap();
    let json = canonicalize(exported.as_value()).unwrap();
    let brc39 = bsv_wallet_toolbox::storage::portable::encrypt_brc39(&exported, PASSWORD_NFC, None)
        .unwrap();
    assert_eq!(&brc39[..4], b"WDAT");

    if std::env::var("RUST_ARTIFACT_OUT").is_ok() {
        let dir = format!("{}/tests/fixtures/portable", env!("CARGO_MANIFEST_DIR"));
        std::fs::write(format!("{dir}/brc38-rust-export.json"), &json).unwrap();
        std::fs::write(format!("{dir}/brc39-rust-export.bin"), &brc39).unwrap();
    }
}

/// The committed Rust-produced BRC-39 artifact (already verified against TS
/// by `portable-rust-verify.test.ts`) must keep decrypting and restoring.
#[tokio::test]
async fn committed_rust_artifact_still_imports() {
    let bytes = fixture_bytes("brc39-rust-export.bin");
    let json = fixture_string("brc38-rust-export.json");
    let decrypted =
        bsv_wallet_toolbox::storage::portable::decrypt_brc39(&bytes, PASSWORD_NFC).unwrap();
    assert_eq!(canonicalize(decrypted.as_value()).unwrap(), json);

    let target = empty_storage().await;
    let result = import_brc38(
        &target,
        &decrypted,
        &Brc38ImportOptions {
            mode: ImportMode::Restore,
        },
    )
    .await
    .unwrap();
    assert_eq!(result.identity_key, fixture_identity_key());
}
