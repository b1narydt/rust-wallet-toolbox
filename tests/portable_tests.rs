/// Merge the TS export into a target whose autoincrement counters are offset
/// by pre-existing data, then verify id remapping end-to-end: rows land under
/// new ids, foreign keys follow them, and the imported remote sync state's
/// id-map values are rewritten through the import id-map.
#[tokio::test]
async fn merge_ts_export_remaps_ids_and_sync_maps() {
    let json = fixture_string("brc38-ts-export.json");
    let original: Value = serde_json::from_str(&json).unwrap();
    let document = parse_brc38_json(&json).unwrap();
    let target = empty_storage().await;

    // Offset the target's autoincrement ids so remapping is observable.
    let now = chrono::Utc::now().naive_utc();
    let other_user_id = target
        .insert_user(
            &bsv_wallet_toolbox::tables::User {
                created_at: now,
                updated_at: now,
                user_id: 0,
                identity_key: "02".repeat(33),
                active_storage: "elsewhere".to_string(),
            },
            None,
        )
        .await
        .unwrap();
    assert_eq!(other_user_id, 1);
    // Offset the transactions counter too, so remapped transaction ids can
    // never coincide with the source's.
    target
        .insert_transaction(
            &bsv_wallet_toolbox::tables::Transaction {
                created_at: now,
                updated_at: now,
                transaction_id: 0,
                user_id: other_user_id,
                proven_tx_id: None,
                status: bsv_wallet_toolbox::status::TransactionStatus::Unprocessed,
                reference: "offset-ref".to_string(),
                is_outgoing: false,
                satoshis: 0,
                description: "autoincrement offset".to_string(),
                version: None,
                lock_time: None,
                txid: None,
                input_beef: None,
                raw_tx: None,
            },
            None,
        )
        .await
        .unwrap();

    let result = import_brc38(
        &target,
        &document,
        &Brc38ImportOptions {
            mode: ImportMode::Merge,
        },
    )
    .await
    .unwrap();
    assert_eq!(result.mode, ImportMode::Merge);
    assert!(result.inserts > 0, "merge into empty user must insert rows");
    assert_ne!(
        result.user_id,
        original["user"]["userId"].as_i64().unwrap(),
        "target user id must differ from the source's (autoincrement offset)"
    );

    // The import-tracking sync state must map source transaction ids to the
    // new target ids.
    let source_storage_key = original["sourceStorage"]["storageIdentityKey"]
        .as_str()
        .unwrap();
    let import_state = target
        .find_sync_states(
            &FindSyncStatesArgs {
                partial: SyncStatePartial {
                    user_id: Some(result.user_id),
                    storage_identity_key: Some(source_storage_key.to_string()),
                    ..Default::default()
                },
                ..Default::default()
            },
            None,
        )
        .await
        .unwrap();
    assert_eq!(import_state.len(), 1);
    let import_map: Value = serde_json::from_str(&import_state[0].sync_map).unwrap();

    let source_tx_id = original["tables"]["transactions"][0]["transactionId"]
        .as_i64()
        .unwrap();
    let target_tx_id = import_map["transaction"]["idMap"][source_tx_id.to_string()]
        .as_i64()
        .expect("merge must record a transaction id mapping");
    let source_output = original["tables"]["outputs"]
        .as_array()
        .unwrap()
        .iter()
        .find(|o| o["transactionId"].as_i64() == Some(source_tx_id))
        .expect("fixture has an output on the first transaction");
    let target_output_id = import_map["output"]["idMap"]
        [source_output["outputId"].as_i64().unwrap().to_string()]
    .as_i64()
    .unwrap();

    // The output landed under its remapped id with its FK following the
    // transaction's remapped id.
    let outputs = target
        .find_outputs(
            &FindOutputsArgs {
                partial: OutputPartial {
                    output_id: Some(target_output_id),
                    ..Default::default()
                },
                ..Default::default()
            },
            None,
        )
        .await
        .unwrap();
    assert_eq!(outputs.len(), 1);
    assert_eq!(outputs[0].transaction_id, target_tx_id);

    // The imported remote sync state maps foreign id 777 to a source
    // transaction id and 778 to a source output id; after merge those values
    // must be rewritten through the import id-map.
    let source_remote_map: Value = original["tables"]["syncStates"]
        .as_array()
        .unwrap()
        .iter()
        .find(|s| s["storageIdentityKey"].as_str() == Some("remote-sync-storage-identity-key"))
        .expect("fixture has the remote sync state")["syncMap"]
        .clone();
    let source_777 = source_remote_map["transaction"]["idMap"]["777"]
        .as_i64()
        .unwrap();
    let source_778 = source_remote_map["output"]["idMap"]["778"]
        .as_i64()
        .unwrap();
    let expected_777 = import_map["transaction"]["idMap"][source_777.to_string()]
        .as_i64()
        .unwrap();
    let expected_778 = import_map["output"]["idMap"][source_778.to_string()]
        .as_i64()
        .unwrap();
    assert_ne!(expected_777, source_777, "offset must force real remapping");
    let remote_state = target
        .find_sync_states(
            &FindSyncStatesArgs {
                partial: SyncStatePartial {
                    user_id: Some(result.user_id),
                    storage_identity_key: Some("remote-sync-storage-identity-key".to_string()),
                    ..Default::default()
                },
                ..Default::default()
            },
            None,
        )
        .await
        .unwrap();
    assert_eq!(
        remote_state.len(),
        1,
        "imported remote sync state must exist"
    );
    let remote_map: Value = serde_json::from_str(&remote_state[0].sync_map).unwrap();
    assert_eq!(
        remote_map["transaction"]["idMap"]["777"].as_i64(),
        Some(expected_777),
        "remote sync map values must be remapped through the import id-map"
    );
    assert_eq!(
        remote_map["output"]["idMap"]["778"].as_i64(),
        Some(expected_778)
    );

    // Merging the same document again must be idempotent on inserts for
    // natural-keyed entities (rows merge, not duplicate).
    let again = import_brc38(
        &target,
        &document,
        &Brc38ImportOptions {
            mode: ImportMode::Merge,
        },
    )
    .await
    .unwrap();
    let tx_count = target
        .count_transactions(&Default::default(), None)
        .await
        .unwrap();
    assert_eq!(
        tx_count,
        original["tables"]["transactions"].as_array().unwrap().len() as i64 + 1,
        "re-merge must not duplicate transactions beyond the offset row (second run: {again:?})"
    );
}

/// A corrupt stored sync map must fail the merge, not be silently replaced
/// with an empty map: the stored id-map is the record of which source rows
/// already landed under which target ids, and overwriting it would make the
/// next round re-insert rows it should have matched.
#[tokio::test]
async fn merge_fails_loudly_on_corrupt_stored_sync_map() {
    let document = parse_brc38_json(&fixture_string("brc38-ts-export.json")).unwrap();
    let original: Value = serde_json::from_str(&fixture_string("brc38-ts-export.json")).unwrap();
    let target = empty_storage().await;

    let now = chrono::Utc::now().naive_utc();
    let user_id = target
        .insert_user(
            &bsv_wallet_toolbox::tables::User {
                created_at: now,
                updated_at: now,
                user_id: 0,
                identity_key: fixture_identity_key(),
                active_storage: "elsewhere".to_string(),
            },
            None,
        )
        .await
        .unwrap();
    let source_key = original["sourceStorage"]["storageIdentityKey"]
        .as_str()
        .unwrap();
    let source_name = original["sourceStorage"]["storageName"].as_str().unwrap();
    target
        .insert_sync_state(
            &bsv_wallet_toolbox::tables::SyncState {
                created_at: now,
                updated_at: now,
                sync_state_id: 0,
                user_id,
                storage_identity_key: source_key.to_string(),
                storage_name: source_name.to_string(),
                status: bsv_wallet_toolbox::status::SyncStatus::Unknown,
                init: false,
                ref_num: "corrupt-map-ref".to_string(),
                sync_map: "not-json{{{".to_string(),
                when: None,
                satoshis: None,
                error_local: None,
                error_other: None,
            },
            None,
        )
        .await
        .unwrap();

    let err = import_brc38(
        &target,
        &document,
        &Brc38ImportOptions {
            mode: ImportMode::Merge,
        },
    )
    .await
    .unwrap_err()
    .to_string();
    assert!(err.contains("corrupt syncMap JSON"), "{err}");

    // The failure aborted before any overwrite: the stored (corrupt) map is
    // intact for inspection and nothing was merged.
    let states = target
        .find_sync_states(
            &FindSyncStatesArgs {
                partial: SyncStatePartial {
                    user_id: Some(user_id),
                    storage_identity_key: Some(source_key.to_string()),
                    ..Default::default()
                },
                ..Default::default()
            },
            None,
        )
        .await
        .unwrap();
    assert_eq!(states.len(), 1);
    assert_eq!(states[0].sync_map, "not-json{{{");
    assert_eq!(
        target
            .count_transactions(&Default::default(), None)
            .await
            .unwrap(),
        0,
        "nothing may merge once the sync state is known corrupt"
    );
}

/// After a merge import, the import-tracking sync state's `when` must equal
/// the latest updated_at merged (TS EntitySyncState.processSyncChunk
/// done-handling). `when` is the `since` a later sync round resumes from;
/// left unset, the next round would re-scan from the beginning of time.
#[tokio::test]
async fn merge_sets_import_sync_state_when_to_latest_merged_updated_at() {
    let json = fixture_string("brc38-ts-export.json");
    let original: Value = serde_json::from_str(&json).unwrap();
    let document = parse_brc38_json(&json).unwrap();
    let target = empty_storage().await;

    let result = import_brc38(
        &target,
        &document,
        &Brc38ImportOptions {
            mode: ImportMode::Merge,
        },
    )
    .await
    .unwrap();

    // Expected: max updated_at over the 12 chunk entity tables (user and
    // syncStates do not travel through the entity sync maps).
    let mut expected: Option<chrono::NaiveDateTime> = None;
    for table in [
        "provenTxs",
        "provenTxReqs",
        "outputBaskets",
        "transactions",
        "commissions",
        "outputs",
        "outputTags",
        "outputTagMaps",
        "txLabels",
        "txLabelMaps",
        "certificates",
        "certificateFields",
    ] {
        for row in original["tables"][table].as_array().unwrap() {
            let at = chrono::NaiveDateTime::parse_from_str(
                row["updated_at"].as_str().unwrap().trim_end_matches('Z'),
                "%Y-%m-%dT%H:%M:%S%.f",
            )
            .unwrap();
            expected = Some(expected.map_or(at, |cur| cur.max(at)));
        }
    }
    let expected = expected.expect("fixture has entity rows");

    let import_state = target
        .find_sync_states(
            &FindSyncStatesArgs {
                partial: SyncStatePartial {
                    user_id: Some(result.user_id),
                    storage_identity_key: Some(
                        original["sourceStorage"]["storageIdentityKey"]
                            .as_str()
                            .unwrap()
                            .to_string(),
                    ),
                    ..Default::default()
                },
                ..Default::default()
            },
            None,
        )
        .await
        .unwrap();
    assert_eq!(import_state.len(), 1);
    assert_eq!(
        import_state[0].when,
        Some(expected),
        "when must record the latest updated_at this import transferred"
    );
}

/// A restore that fails mid-way must roll back completely and surface the
/// original insert error — the target must be left exactly as found
/// (restorable), never partially written.
#[tokio::test]
async fn restore_failure_rolls_back_and_surfaces_the_original_error() {
    // Two provenTxs with distinct ids but the same txid pass BRC-38
    // validation (which checks id uniqueness only) and then violate the
    // proven_txs.txid UNIQUE constraint mid-transaction.
    let mut doc = minimal_document();
    // minimal_document carries only what the validators need; decoding into
    // table structs additionally needs the full settings row.
    doc["sourceStorage"]["dbtype"] = Value::String("SQLite".to_string());
    doc["sourceStorage"]["maxOutputScript"] = Value::from(1024);
    let proven = |id: i64| {
        serde_json::json!({
            "created_at": "2026-01-02T03:04:05.006Z",
            "updated_at": "2026-01-02T03:04:05.006Z",
            "provenTxId": id,
            "txid": "duplicate-txid",
            "height": 1,
            "index": 0,
            "merklePath": "AA==",
            "rawTx": "AA==",
            "blockHash": "block-hash",
            "merkleRoot": "merkle-root"
        })
    };
    doc["tables"]["provenTxs"] = serde_json::json!([proven(1), proven(2)]);
    let poisoned = parse_brc38_json(&doc.to_string()).unwrap();
    let target = empty_storage().await;
    let options = Brc38ImportOptions {
        mode: ImportMode::Restore,
    };

    let err = import_brc38(&target, &poisoned, &options)
        .await
        .unwrap_err()
        .to_string();
    assert!(
        err.contains("UNIQUE") || err.contains("unique"),
        "the original constraint violation must surface: {err}"
    );

    // Rollback left the target fully empty...
    assert_eq!(
        target.count_users(&Default::default(), None).await.unwrap(),
        0
    );
    assert_eq!(
        target
            .count_proven_txs(&Default::default(), None)
            .await
            .unwrap(),
        0
    );
    // ...and healthy: a valid restore into the same target still succeeds.
    let good = parse_brc38_json(&fixture_string("brc38-ts-export.json")).unwrap();
    import_brc38(&target, &good, &options).await.unwrap();
}

