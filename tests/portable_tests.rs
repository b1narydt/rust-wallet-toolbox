#[tokio::test]
async fn restore_ts_export_and_reexport_matches_byte_level() {
    let json = fixture_string("brc38-ts-export.json");
    let document = parse_brc38_json(&json).unwrap();
    let target = empty_storage().await;

    let result = import_brc38(
        &target,
        &document,
        &Brc38ImportOptions {
            mode: ImportMode::Restore,
        },
    )
    .await
    .unwrap();
    assert_eq!(result.mode, ImportMode::Restore);
    assert_eq!(result.identity_key, fixture_identity_key());
    assert_eq!(result.updates, 0);

    // Re-export from the restored target and compare the user and tables
    // sections byte-for-byte with the TS original. sourceStorage and
    // exportedAt legitimately differ (different storage, different time).
    let reexported = export_brc38_json(&target, &fixture_identity_key())
        .await
        .unwrap();
    let mut original: Value = serde_json::from_str(&json).unwrap();
    let reexported: Value = serde_json::from_str(&reexported).unwrap();
    strip_unmodeled_fields(&mut original);
    assert_eq!(
        canonicalize(&reexported["user"]).unwrap(),
        canonicalize(&original["user"]).unwrap(),
        "restored user must re-export identically"
    );
    assert_eq!(
        canonicalize(&reexported["tables"]).unwrap(),
        canonicalize(&original["tables"]).unwrap(),
        "restored tables must re-export identically (ids, timestamps, bytes)"
    );
}

