fn fixture_identity_key() -> String {
    let meta: Value = serde_json::from_str(&fixture_string("meta.json")).unwrap();
    meta["identityKey"].as_str().unwrap().to_string()
}

async fn empty_storage() -> SqliteStorage {
    let config = StorageConfig {
        url: "sqlite::memory:".to_string(),
        ..Default::default()
    };
    let storage = SqliteStorage::new_sqlite(config, Chain::Test)
        .await
        .unwrap();
    storage.migrate_database().await.unwrap();
    storage.make_available().await.unwrap();
    storage
}

/// Drop the two provenTxReq fields the Rust storage schema does not model
/// (`wasBroadcast`, `rebroadcastAttempts` -- storage parity audit,
/// rust-wallet-toolbox#34). This is the single documented normalization
/// applied before byte comparison; everything else must match exactly.
fn strip_unmodeled_fields(document: &mut Value) {
    if let Some(reqs) = document["tables"]["provenTxReqs"].as_array_mut() {
        for req in reqs {
            if let Some(map) = req.as_object_mut() {
                map.remove("wasBroadcast");
                map.remove("rebroadcastAttempts");
            }
        }
    }
}

